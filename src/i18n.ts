export type Lang = "en" | "ko" | "zh";
const DICTS: Record<Lang, Dict> = { en, ko, zh };
const LOCALES: Record<Lang, string> = { en: "en-US", ko: "ko-KR", zh: "zh-CN" };

let current: Dict = en;
let locale = "en-US";
let code: Lang = "en";

/**
 * The interface language for a saved preference and Obsidian's own language. "auto" — or any value this
 * version doesn't know, e.g. from a newer data.json — follows Obsidian: ko… → Korean, zh… (zh, zh-TW) → Chinese.
 */
export function resolveLanguage(pref: string, obsidian: string): Lang {
  const lang = (pref === "en" || pref === "ko" || pref === "zh" ? pref : obsidian || "en").toLowerCase();
  return lang.startsWith("ko") ? "ko" : lang.startsWith("zh") ? "zh" : "en";
}

export function setLanguage(pref: string): void {
  code = resolveLanguage(pref, getLanguage());
  current = DICTS[code];
  locale = LOCALES[code];
}

export const t = (): Dict => current;
export const loc = (): string => locale;
export const lang = (): Lang => code;
export type { Dict };
